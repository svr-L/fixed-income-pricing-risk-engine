"""Hull-White 1F: exact curve fit, analytic swaptions, calibration to the strip."""

from datetime import date

from fi_pricing import core as fc
from fi_pricing.hull_white import (
    HullWhiteParams,
    calibrate_hull_white,
    caplet_instruments_from_surface,
    caplet_price,
    swaption_from_schedule,
    swaption_price,
    zero_bond_option,
)
from fi_pricing.market_data import CURVE_DAYS, CURVE_ZERO_RATES
from fi_pricing.volatility import implied_volatility, strip_caplet_vol_surface

VALUE_DATE = date(2025, 1, 2)
curve = fc.DiscountCurve(
    CURVE_DAYS, CURVE_ZERO_RATES, VALUE_DATE, interpolation="log_linear_df"
)
params = HullWhiteParams(a=0.05, sigma=0.010)

# ---------------------------------------------------------------------------
# The property that makes the model usable: it reprices today's curve exactly.
# ---------------------------------------------------------------------------
print("Exact fit to the initial term structure")
r0 = curve.instantaneous_forward(0.0)
worst = 0.0
for maturity in (1.0, 5.0, 10.0, 30.0):
    from fi_pricing.hull_white import zero_bond_price

    model = zero_bond_price(params, curve, 0.0, maturity, r0)
    market = curve.df_days(maturity * 365.0)
    worst = max(worst, abs(model - market))
    print(f"  P(0,{maturity:4.0f})  model {model:.14f}  market {market:.14f}")
print(f"  worst absolute error       : {worst:.2e}")

# ---------------------------------------------------------------------------
# Analytic parities that any implementation must satisfy.
# ---------------------------------------------------------------------------
call = zero_bond_option(params, curve, 2.0, 5.0, 0.90, 1)
put = zero_bond_option(params, curve, 2.0, 5.0, 0.90, -1)
parity = curve.df_days(5 * 365.0) - 0.90 * curve.df_days(2 * 365.0)
print("\nBond option put-call parity")
print(f"  C - P                      : {call - put:+.14f}")
print(f"  P(0,S) - K P(0,T)          : {parity:+.14f}")

times = tuple(1.0 + i for i in range(1, 6))
accruals = (1.0,) * 5
payer = swaption_price(params, curve, 1.0, times, accruals, 0.0325)
receiver = swaption_price(params, curve, 1.0, times, accruals, 0.0325, payer=False)
annuity = sum(a * curve.df_days(t * 365.0) for t, a in zip(times, accruals, strict=True))
forward = (curve.df_days(365.0) - curve.df_days(times[-1] * 365.0)) / annuity
print("\nSwaption payer-receiver parity (Jamshidian)")
print(f"  payer - receiver           : {payer - receiver:+.12f}")
print(f"  forward swap value         : {(forward - 0.0325) * annuity:+.12f}")

# ---------------------------------------------------------------------------
# Mean reversion shows up as a decaying implied-vol term structure.
# ---------------------------------------------------------------------------
print("\nImplied Black caplet vols generated by the model")
for reset in (1.0, 2.0, 5.0, 10.0):
    payment, accrual = reset + 0.5, 0.5
    df_payment = curve.df_days(payment * 365.0)
    fwd = (curve.df_days(reset * 365.0) / df_payment - 1.0) / accrual
    price = caplet_price(params, curve, reset, payment, accrual, fwd)
    vol = implied_volatility(price / (accrual * df_payment), fwd, fwd, reset, 1)
    print(f"  reset {reset:5.1f}y  F {fwd:.4%}  implied vol {vol:.4%}")

# ---------------------------------------------------------------------------
# Calibration to the stripped caplet surface.
# ---------------------------------------------------------------------------
surface = strip_caplet_vol_surface(
    VALUE_DATE, date(2025, 4, 2),
    [date(2027, 4, 2), date(2030, 4, 2), date(2035, 4, 2)],
    [0.02, 0.03, 0.04],
    [[0.24, 0.22, 0.23], [0.22, 0.205, 0.215], [0.21, 0.20, 0.21]],
    2, curve,
)
instruments = caplet_instruments_from_surface(
    VALUE_DATE, date(2025, 4, 2), date(2035, 4, 2), 0.03, 2, curve, surface
)
result = calibrate_hull_white(instruments, curve)
average = sum(i.target_price for i in instruments) / len(instruments)
print("\nCalibration to the stripped caplet strip")
print(f"  targets                    : {len(instruments)} caplets")
print(f"  mean reversion a           : {result.params.a:.6f}")
print(f"  volatility sigma           : {result.params.sigma:.6f}")
print(f"  RMSE                       : {result.rmse:.3e}")
print(f"  RMSE / average premium     : {result.rmse / average:.2%}")
print("  (a two-parameter model cannot fit a smile-bearing strip exactly)")

# ---------------------------------------------------------------------------
# A swaption priced from calendar dates with the calibrated parameters.
# ---------------------------------------------------------------------------
premium = swaption_from_schedule(
    result.params, VALUE_DATE, date(2027, 1, 4), date(2027, 1, 4), date(2032, 1, 2),
    0.032, curve, notional=1_000_000,
)
print(f"\n5y swaption into 5y, strike 3.2% : {premium:,.2f}")
